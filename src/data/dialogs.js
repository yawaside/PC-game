const give = (g, id, n = 1) => {
  const k = g.inv.add(id, n);
  if (k > 0) g.ui.toast(`Получено: ${ITEMS[id].name}${n > 1 ? ' ×' + n : ''}`, 'good');
  else g.ui.toast(`Нет места для ${ITEMS[id].name}! Освободите рюкзак.`, 'warn');
  return k;
};
export const giveItem = give;

const learnAbility = (g, id, label) => {
  if (g.stats.abilities[id]) return;
  g.stats.abilities[id] = true;
  g.ui.toast(`Установлена программа: ${label}!`, 'good', 4500);
  g.audio.sfx('learn');
  g.events.emit('abilityLearned', id);
};
export { learnAbility };

/** Подсказка Скрепыша: что делать дальше. */
export function nextHint(g) {
  const f = g.flag.bind(g);
  if (!f('met_klara')) return 'Подойдите к Кларе — та самая золотая штука-щит недалеко от старта. Нажмите E.';
  if (!f('firewall_given')) return f('tutorial_birds') ? 'Победите трёх Popup-птиц возле Клары. ЛКМ — быстрый удар, ПКМ — тяжёлый.' : 'Поговорите с Кларой ещё раз.';
  if (!f('boss_trojan')) return 'Идите в «Мои документы» — врата на северо-западе площади. Там вас ждёт Помощник.exe. Кажется, вполне милый.';
  if (g.act < 3) {
    const left = [];
    if (!f('boss_ransom')) left.push('Корзина (нужен двойной прыжок)');
    if (!f('boss_hydra')) left.push('Папка Temp (нужен рывок)');
    if (!f('boss_commandant')) left.push('Автозагрузка');
    if (!f('reg_done')) left.push('Реестр');
    if (!f('diskd_done')) left.push('Диск D:');
    if (left.length) return `Осталось освободить: ${left.join(', ')}. Клара ждёт вестей.`;
    if (!f('boss_admiral')) return 'Путь в Интернет открыт — врата на востоке. Понадобится «Ссылка» (F).';
    return 'Поговорите с Кларой: Обновление уже близко.';
  }
  if (!f('boss_update')) return 'Мир стирается! Скорее в BIOS — люк в центре площади открыт.';
  return 'Поздравляю! Теперь можно просто побродить и собрать все скрытые файлы (H). Я бы на вашем месте проверил крыши.';
}

