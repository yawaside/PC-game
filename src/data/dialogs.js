/** Выбор диалога при разговоре с NPC. Возвращает id диалога (или массив реплик). */
const hooks = [];
/** Другие модули добавляют сюда условия для Клары: {when(g), dialog} — первые сверху важнее. */
export const KLARA_HOOKS = hooks;

export const NPC_TALK = {
  klara: (g) => {
    if (!g.flag('met_klara')) return 'klara_1';
    if (g.flag('tutorial_birds') && !g.flag('birds_done')) return 'klara_birds';
    if (g.flag('birds_done') && !g.flag('firewall_given')) return 'klara_2';
    for (const h of hooks) if (h.when(g)) return h.dialog;
    return 'klara_idle';
  },
  clippy: () => 'clippy_1',
  calc: () => 'calc_1',
  notepad: () => 'notepad_1',
  taskman: (g) => {
    if (g.quests.isDone('s_taskman')) return null;
    if (!g.quests.has('s_taskman')) return 'taskman_1';
    return g.quests.isReady('s_taskman') ? 'taskman_done' : 'taskman_wait';
  },
  tray: () => 'tray_1',
};
